CREATE TABLE IF NOT EXISTS users (
  id INT NOT NULL AUTO_INCREMENT,
  ad_guid CHAR(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  ad_username VARCHAR(255) DEFAULT NULL,
  name VARCHAR(255) DEFAULT NULL,
  disabled_at DATETIME DEFAULT NULL,
  auth_version INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_users_ad_guid (ad_guid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS otp_profiles (
  id INT NOT NULL AUTO_INCREMENT,
  user_id INT NOT NULL,
  name VARCHAR(255) NOT NULL,
  issuer VARCHAR(255) DEFAULT '',
  secret_encrypted TEXT NOT NULL,
  algorithm ENUM('SHA1','SHA256','SHA512') DEFAULT 'SHA1',
  digits TINYINT DEFAULT 6,
  period SMALLINT DEFAULT 30,
  color VARCHAR(7) DEFAULT '#6366f1',
  icon VARCHAR(50) DEFAULT 'fa-shield-halved',
  hide_code TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_otp_profiles_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
  bucket CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  window_id BIGINT UNSIGNED NOT NULL,
  attempts SMALLINT UNSIGNED NOT NULL,
  PRIMARY KEY (bucket),
  KEY idx_login_attempts_window (window_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS user_access_audit (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  actor_id INT NOT NULL,
  target_id INT NOT NULL,
  action ENUM('enabled','disabled') NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;
